#!/usr/bin/env python3
"""Generate ytenx/static/css/rare-font.css from the Jigmo webfont service.

The upstream stylesheet assigns whole chunks (including Latin and the URO) to
'Jigmo TC', and on macOS Chrome any system font placed before it claims rare
ideographs and draws a missing-glyph box. This keeps the upstream font files
but clips each face's unicode-range to the CJK extension blocks, so the family
can lead the font stack without affecting common characters.
"""
import argparse
import re
import urllib.request
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_TARGET = ROOT / 'ytenx' / 'static' / 'css' / 'rare-font.css'
SOURCE = 'https://jigmo.digitalhumanities.dev/'
FAMILY = 'ytenx rare'

# CJK Extension A, the compatibility ideographs supplement, and Extensions B–J.
RARE_BLOCKS = (
    (0x3400, 0x4DBF),
    (0x20000, 0x2A6DF),
    (0x2A700, 0x2EE5F),
    (0x2F800, 0x2FA1F),
    (0x30000, 0x323AF),
)


def parse_faces(css):
    for body in re.findall(r'@font-face\s*{(.*?)}', css, re.S):
        if "font-family: 'Jigmo TC'" not in body:
            continue
        src = re.search(r"url\('([^']+)'\)", body).group(1)
        ranges = [
            (int(a, 16), int(b or a, 16))
            for a, b in re.findall(r'U\+([0-9A-Fa-f]+)(?:-([0-9A-Fa-f]+))?', body)
        ]
        yield src, ranges


def clip(ranges):
    out = []
    for lo, hi in ranges:
        for blo, bhi in RARE_BLOCKS:
            a, b = max(lo, blo), min(hi, bhi)
            if a <= b:
                out.append((a, b))
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--target', default=str(DEFAULT_TARGET))
    args = parser.parse_args()

    req = urllib.request.Request(SOURCE + 'jigmo-tc.css', headers={'User-Agent': 'ytenx-build'})
    with urllib.request.urlopen(req) as resp:
        css = resp.read().decode('utf-8')

    faces = []
    for src, ranges in parse_faces(css):
        clipped = clip(ranges)
        if not clipped:
            continue
        unicode_range = ', '.join(
            'U+%X' % a if a == b else 'U+%X-%X' % (a, b) for a, b in clipped
        )
        faces.append(
            "@font-face {\n"
            "  font-family: '%s';\n"
            "  font-style: normal;\n"
            "  font-weight: 400;\n"
            "  font-display: swap;\n"
            "  src: url('%s%s') format('woff2');\n"
            "  unicode-range: %s;\n"
            "}\n" % (FAMILY, SOURCE, src, unicode_range)
        )

    header = (
        '/* Generated by scripts/build_rare_font_css.py from %sjigmo-tc.css.\n'
        ' * Jigmo (CC0) limited to CJK Extension A, B–J and compatibility supplement. */\n'
        % SOURCE
    )
    Path(args.target).write_text(header + '\n'.join(faces), encoding='utf-8')
    print('Wrote %d faces to %s' % (len(faces), args.target))


if __name__ == '__main__':
    main()
